class Font {
public:
    void upload_gpu() {
        const int CHAR_W = 8, CHAR_H = 8;
        const int ATLAS_W = 128, ATLAS_H = 48;
        std::vector<unsigned char> pixels(ATLAS_W * ATLAS_H * 4, 0);

        for (int ch = 0; ch < 95; ch++) {
            int ax = (ch % 16) * CHAR_W;
            int ay = (ch / 16) * CHAR_H;
            for (int row = 0; row < 8; row++) {
                unsigned char bits = FONT_DATA[ch][row];
                for (int col = 0; col < 8; col++) {
                    if (bits & (0x80 >> col)) {
                        int px = ax + col;
                        int py = ay + row;
                        int idx = (py * ATLAS_W + px) * 4;
                        pixels[idx + 0] = 255;
                        pixels[idx + 1] = 255;
                        pixels[idx + 2] = 255;
                        pixels[idx + 3] = 255;
                    }
                }
            }
        }

        glGenTextures(1, &texture_);
        glBindTexture(GL_TEXTURE_2D, texture_);
        glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA, ATLAS_W, ATLAS_H, 0,
                     GL_RGBA, GL_UNSIGNED_BYTE, pixels.data());
        glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
        glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
        glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
        glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
    }

    void draw_text(const std::string& text, float x, float y, float scale,
                   glm::vec4 color, GLuint hud_shader, int screen_w, int screen_h) {
        glUseProgram(hud_shader);
        glUniform2f(glGetUniformLocation(hud_shader, "resolution"), (float)screen_w, (float)screen_h);
        glUniform1i(glGetUniformLocation(hud_shader, "useTexture"), 1);
        glUniform4fv(glGetUniformLocation(hud_shader, "color"), 1, &color[0]);
        glActiveTexture(GL_TEXTURE0);
        glBindTexture(GL_TEXTURE_2D, texture_);

        glBindVertexArray(vao_);
        for (char c : text) {
            if (c < 32 || c > 127) continue;
            int idx = c - 32;
            float u0 = (float)(idx % 16) * 8.0f / 128.0f;
            float v0 = (float)(idx / 16) * 8.0f / 48.0f;
            float u1 = u0 + 8.0f / 128.0f;
            float v1 = v0 + 8.0f / 48.0f;

            float w = 8.0f * scale;
            float h = 8.0f * scale;
            float verts[] = {
                x, y,     u0, v0,
                x+w, y,   u1, v0,
                x+w, y+h, u1, v1,
                x, y,     u0, v0,
                x+w, y+h, u1, v1,
                x, y+h,   u0, v1,
            };
            glBindBuffer(GL_ARRAY_BUFFER, vbo_);
            glBufferSubData(GL_ARRAY_BUFFER, 0, sizeof(verts), verts);
            glDrawArrays(GL_TRIANGLES, 0, 6);
            x += w;
        }
        glBindVertexArray(0);
    }

    float text_width(const std::string& text, float scale) {
        return text.length() * 8.0f * scale;
    }

    void init() {
        glGenVertexArrays(1, &vao_);
        glGenBuffers(1, &vbo_);
        glBindVertexArray(vao_);
        glBindBuffer(GL_ARRAY_BUFFER, vbo_);
        glBufferData(GL_ARRAY_BUFFER, sizeof(float) * 6 * 4, nullptr, GL_DYNAMIC_DRAW);
        glVertexAttribPointer(0, 2, GL_FLOAT, GL_FALSE, 4 * sizeof(float), (void*)0);
        glEnableVertexAttribArray(0);
        glVertexAttribPointer(1, 2, GL_FLOAT, GL_FALSE, 4 * sizeof(float), (void*)(2 * sizeof(float)));
        glEnableVertexAttribArray(1);
        glBindVertexArray(0);
        upload_gpu();
    }

    void cleanup() {
        if (vao_) glDeleteVertexArrays(1, &vao_);
        if (vbo_) glDeleteBuffers(1, &vbo_);
        if (texture_) glDeleteTextures(1, &texture_);
    }

private:
    GLuint vao_ = 0, vbo_ = 0, texture_ = 0;
};
